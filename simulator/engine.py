"""Match engine: possession-sequence loop over two 45-minute halves.

Deterministic: all randomness flows through a single random.Random(seed),
except shot decisions which use a decoupled stream (self._srng) so that
tuning the shot rate never perturbs pass-completion statistics.

AT-01: same seed + teams -> identical events and snapshots.
"""

from __future__ import annotations

import math
import random
from datetime import UTC, datetime, timedelta

from core.formations import starting_xi
from core.pitch import PITCH_LENGTH_M, PITCH_WIDTH_M
from core.schemas import (
    EventType,
    MatchEvent,
    Outcome,
    Player,
    PlayerPosition,
    PositionSnapshot,
    Role,
    Team,
    TeamStyle,
)
from simulator.positions import build_snapshot

# ---------------------------------------------------------------------------
# Constants
# ---------------------------------------------------------------------------

HALF_S = 2700  # 45 minutes in seconds

# Fixed reference so event_time is deterministic (same seed -> same timestamps)
_EPOCH = datetime(2026, 1, 1, tzinfo=UTC)

# Probability of a pressure event generated by the defending team per action
_PRESS_RATE: dict[TeamStyle, float] = {
    TeamStyle.POSSESSION: 0.22,
    TeamStyle.DIRECT:     0.18,
    TeamStyle.HIGH_PRESS: 0.38,
}

# (min, max) on-ball actions per possession sequence
_SEQ_LEN: dict[TeamStyle, tuple[int, int]] = {
    TeamStyle.POSSESSION: (5, 12),
    TeamStyle.DIRECT:     (2,  6),
    TeamStyle.HIGH_PRESS: (3,  8),
}

# Probability of choosing pass vs carry for each action
_P_PASS: dict[TeamStyle, float] = {
    TeamStyle.POSSESSION: 0.72,
    TeamStyle.DIRECT:     0.60,
    TeamStyle.HIGH_PRESS: 0.65,
}

# "Target" pass distance used by the receiver-weight function
_TARGET_DIST: dict[TeamStyle, float] = {
    TeamStyle.POSSESSION: 17.0,
    TeamStyle.DIRECT:     27.0,
    TeamStyle.HIGH_PRESS: 21.0,
}

# Relative likelihood of each role being selected to carry the ball
_CARRIER_W: dict[Role, float] = {
    Role.GK: 0.3, Role.CB: 0.7, Role.FB: 1.1,
    Role.DM: 1.6, Role.CM: 2.0, Role.AM: 2.0,
    Role.W:  1.8, Role.ST: 1.7,
}


# ---------------------------------------------------------------------------
# Pure helpers
# ---------------------------------------------------------------------------

def _cx(v: float) -> float:
    return max(0.0, min(PITCH_LENGTH_M, v))


def _cy(v: float) -> float:
    return max(0.0, min(PITCH_WIDTH_M, v))


def _pass_p(passing: int, length_m: float, pressure: float, style: TeamStyle) -> float:
    """Pass-completion probability, tuned to hit 78–88 % completion target."""
    base  = 0.84 + (passing / 99) * 0.12           # 0.84–0.96
    lp    = max(0.0, (length_m - 15.0) / 130.0)    # gentle length penalty
    pp    = pressure * 0.18
    bonus = 0.03 if style == TeamStyle.POSSESSION else 0.0
    return max(0.45, min(0.96, base - lp - pp + bonus))


def _receiver_weight(
    passer_x: float, passer_y: float,
    rx: float, ry: float,
    style: TeamStyle,
) -> float:
    """Weight for choosing a receiver from the snapshot; biased by style and forward progress."""
    dist = max(1.0, math.hypot(rx - passer_x, ry - passer_y))
    fwd  = rx - passer_x  # positive = toward goal

    # Gaussian preference centred on the style's target pass distance
    td      = _TARGET_DIST[style]
    d_score = math.exp(-((dist - td) ** 2) / (2.0 * td ** 2))

    # Modest forward bias: players behind the passer heavily discounted
    fwd_score = max(0.05, (fwd + 15.0) / 55.0)   # ~0.05 at fwd=-15, 1.0 at fwd=40

    return max(0.01, d_score * fwd_score)


def _interception_point(
    bx: float, by: float,
    rx: float, ry: float,
    def_positions: list[PlayerPosition],
    rng: random.Random,
) -> tuple[float, float, PlayerPosition | None]:
    """Return (ix, iy, defender) where the pass is interrupted.

    Finds the defender nearest to the pass line and projects them onto it.
    The intercept falls in the middle 20–80 % of the pass.
    Returns None for the defender if def_positions is empty (should not occur).
    """
    dx, dy   = rx - bx, ry - by
    pass_len = math.hypot(dx, dy)
    if pass_len < 0.5 or not def_positions:
        return rx, ry, def_positions[0] if def_positions else None

    ux, uy = dx / pass_len, dy / pass_len

    best_t   = 0.5
    best_def = def_positions[0]
    best_d   = float("inf")

    for dp in def_positions:
        # Scalar projection onto the pass unit vector
        t_raw    = ((dp.x - bx) * ux + (dp.y - by) * uy) / pass_len
        t_c      = max(0.20, min(0.80, t_raw))
        cx_line  = bx + t_c * dx
        cy_line  = by + t_c * dy
        perp     = math.hypot(dp.x - cx_line, dp.y - cy_line)
        if perp < best_d:
            best_d   = perp
            best_t   = t_c
            best_def = dp

    t_final = max(0.15, min(0.85, best_t + rng.uniform(-0.1, 0.1)))
    return _cx(bx + t_final * dx), _cy(by + t_final * dy), best_def


def _shot_result(finishing: int, dist_m: float, rng: random.Random) -> tuple[bool, Outcome]:
    """Return (is_goal, Outcome) for a shot."""
    p_on = max(0.30, 0.78 - dist_m / 65.0)
    if rng.random() >= p_on:
        return False, Outcome.OFF_TARGET
    p_goal = max(0.08, (finishing / 99) * 0.55 * max(0.0, 1.0 - dist_m / 38.0))
    if rng.random() < p_goal:
        return True, Outcome.ON_TARGET
    return False, rng.choice([Outcome.SAVED, Outcome.BLOCKED])


# ---------------------------------------------------------------------------
# Engine
# ---------------------------------------------------------------------------

class MatchEngine:
    def __init__(
        self,
        home_team: Team,
        away_team: Team,
        players: list[Player],
        seed: int,
        match_id: str,
        scenario_id: str,
    ) -> None:
        self._teams   = [home_team, away_team]
        self._rng     = random.Random(seed)           # game-flow RNG
        self._srng    = random.Random(seed ^ 0x5A5A)  # shot-decisions RNG (decoupled)
        self._seed    = seed
        self._mid     = match_id
        self._sid     = scenario_id

        self._xi: list[list[Player]] = [
            starting_xi(
                [p for p in players if p.team_id == home_team.team_id], home_team.formation
            ),
            starting_xi(
                [p for p in players if p.team_id == away_team.team_id], away_team.formation
            ),
        ]

        self._events:    list[MatchEvent]       = []
        self._snapshots: list[PositionSnapshot] = []
        self._ev_n           = 0
        self._sn_n           = 0
        self._last_clock     = 0
        self._carrier: Player | None            = None
        self._last_scored_team: str | None      = None

    # ------------------------------------------------------------------
    # Public
    # ------------------------------------------------------------------

    def run(self) -> tuple[list[MatchEvent], list[PositionSnapshot]]:
        """Simulate a full match and return (events, snapshots).

        Events are returned sorted by (match_clock_s, emission-order) so that
        pressure events (deferred until outcome is known) appear before the
        action they apply to despite being appended later.
        """
        bx, by   = PITCH_LENGTH_M / 2, PITCH_WIDTH_M / 2
        poss_idx = 0   # home kicks off first half
        poss_id  = 0
        clock    = 0

        for period in (1, 2):
            if period == 2:
                poss_idx = 1   # away kicks off second half
                bx, by   = PITCH_LENGTH_M / 2, PITCH_WIDTH_M / 2
                clock    = max(clock, HALF_S)

            end_clock = HALF_S * period

            # Half kickoff
            clock, self._carrier = self._emit_kickoff(
                poss_idx, clock, end_clock, period, poss_id, bx, by
            )

            while clock < end_clock:
                lo, hi = _SEQ_LEN[self._teams[poss_idx].style]
                seq    = self._rng.randint(lo, hi)

                bx, by, clock, poss_id, changed, new_carrier = self._possession(
                    poss_idx, 1 - poss_idx, bx, by, clock, period, poss_id, seq, end_clock
                )

                if changed and clock < end_clock:
                    # Flip coordinates to new possessing team's frame
                    bx      = _cx(PITCH_LENGTH_M - bx)
                    by      = _cy(PITCH_WIDTH_M  - by)
                    poss_idx = 1 - poss_idx
                    poss_id += 1

                    if self._last_scored_team is not None:
                        # Goal: conceding team (now poss_idx) kicks off
                        self._last_scored_team = None
                        bx, by = PITCH_LENGTH_M / 2, PITCH_WIDTH_M / 2
                        clock, self._carrier = self._emit_kickoff(
                            poss_idx, clock, end_clock, period, poss_id, bx, by
                        )
                    elif new_carrier is not None:
                        # Normal possession change: winner of ball is new carrier
                        self._carrier = new_carrier
                    else:
                        # Non-goal shot: pick a central player as restart carrier
                        self._carrier = self._pick_kick(poss_idx)

            # Period end — clock must be ≥ last emitted clock
            pe_clock = max(self._last_clock, end_clock)
            self._ev(EventType.PERIOD_END, pe_clock, period, poss_id,
                     team_id=None, player_id=None)

        # Sort so deferred pressure events appear before the action they precede
        self._events.sort(key=lambda e: (e.match_clock_s, int(e.event_id[3:])))
        return self._events, self._snapshots

    # ------------------------------------------------------------------
    # Possession sequence
    # ------------------------------------------------------------------

    def _possession(
        self,
        pi: int, di: int,
        bx: float, by: float,
        clock: int, period: int, poss_id: int,
        seq: int, end_clock: int,
    ) -> tuple[float, float, int, int, bool, Player | None]:
        """Run one possession sequence.

        Returns (bx, by, clock, poss_id, changed, new_carrier).
        new_carrier is None when possession changed via a shot (caller resets it).
        """
        team    = self._teams[pi]
        dteam   = self._teams[di]
        changed = False
        carrier = self._carrier or self._pick_kick(pi)

        for _ in range(seq):
            if clock >= end_clock:
                break

            # --- Pressure: decide now, emit AFTER the action (outcome then known) ---
            pending: tuple[str, str, float, float, int] | None = None
            if self._rng.random() < _PRESS_RATE[dteam.style]:
                px  = _cx(bx + self._rng.uniform(-5, 5))
                py  = _cy(by + self._rng.uniform(-5, 5))
                dt  = self._rng.randint(1, 2)
                pc  = min(clock + dt, end_clock)
                pres = self._pick(di)
                pending = (dteam.team_id, pres.player_id, px, py, pc)
                clock   = pc
                if clock >= end_clock:
                    break

            # --- Action: pass or carry ---
            if self._rng.random() < _P_PASS[team.style]:
                bx, by, clock, changed, carrier = self._do_pass(
                    pi, di, bx, by, clock, period, poss_id, end_clock, carrier
                )
            else:
                bx, by, clock, changed, carrier = self._do_carry(
                    pi, di, bx, by, clock, period, poss_id, end_clock, carrier
                )

            # --- Emit pressure with outcome determined by the action ---
            if pending is not None:
                tid, pid, px, py, pc = pending
                self._ev(EventType.PRESSURE, pc, period, poss_id,
                         team_id=tid, player_id=pid, x=px, y=py,
                         outcome=Outcome.WON if changed else Outcome.LOST)

            if changed or clock >= end_clock:
                break

            # --- Shot: only when the current carrier is in the final third ---
            if bx >= 68.0 and self._srng.random() < 0.030:
                sx   = _cx(bx + self._srng.uniform(-4, 8))
                sy   = _cy(by + self._srng.uniform(-8, 8))
                dist = math.hypot(PITCH_LENGTH_M - sx, sy - PITCH_WIDTH_M / 2)
                goal, out = _shot_result(carrier.ratings.finishing, dist, self._srng)

                clock = min(clock + self._rng.randint(1, 3), end_clock)
                self._ev(EventType.SHOT, clock, period, poss_id,
                         team_id=team.team_id, player_id=carrier.player_id,
                         x=sx, y=sy, outcome=out)

                if goal and clock < end_clock:
                    clock = min(clock + 1, end_clock)
                    self._ev(EventType.GOAL, clock, period, poss_id,
                             team_id=team.team_id, player_id=carrier.player_id,
                             x=sx, y=sy)
                    self._last_scored_team = team.team_id

                bx, by  = PITCH_LENGTH_M / 2, PITCH_WIDTH_M / 2
                changed = True
                carrier = None   # caller will assign new carrier via kickoff or pick
                break

        self._carrier = carrier
        return bx, by, clock, poss_id, changed, carrier

    # ------------------------------------------------------------------
    # Pass (snapshot-first)
    # ------------------------------------------------------------------

    def _do_pass(
        self,
        pi: int, di: int,
        bx: float, by: float,
        clock: int, period: int, poss_id: int,
        end_clock: int,
        carrier: Player,
    ) -> tuple[float, float, int, bool, Player]:
        team  = self._teams[pi]
        dteam = self._teams[di]

        pressure = self._rng.uniform(0.0, 0.65)

        # Build snapshot FIRST (consumes 44 RNG calls always).
        # Passer placed exactly at (bx, by); receiver chosen from resulting positions.
        emit_snap = bx >= 35.0
        snap_id   = self._snap_id() if emit_snap else "_tmp"
        snap      = build_snapshot(
            snapshot_id=snap_id,
            match_id=self._mid,
            match_clock_s=clock,
            poss_team=team,
            def_team=dteam,
            poss_xi=self._xi[pi],
            def_xi=self._xi[di],
            ball_x=bx,
            ball_y=by,
            rng=self._rng,
            carrier_id=carrier.player_id,
        )
        if emit_snap:
            self._snapshots.append(snap)

        # Teammates (not GK, not passer) as candidate receivers
        poss_pos = [
            p for p in snap.positions
            if p.team_id == team.team_id
            and p.role != Role.GK
            and p.player_id != carrier.player_id
        ]
        if not poss_pos:  # degenerate guard
            poss_pos = [
                p for p in snap.positions if p.team_id == team.team_id
            ]

        def_pos = [p for p in snap.positions if p.team_id == dteam.team_id]

        weights  = [_receiver_weight(bx, by, p.x, p.y, team.style) for p in poss_pos]
        rec_spos = self._rng.choices(poss_pos, weights=weights, k=1)[0]

        receiver = next(p for p in self._xi[pi] if p.player_id == rec_spos.player_id)
        length   = max(1.0, math.hypot(rec_spos.x - bx, rec_spos.y - by))
        p_comp   = _pass_p(carrier.ratings.passing, length, pressure, team.style)
        complete = self._rng.random() < p_comp

        out_snap_id: str | None = snap_id if emit_snap else None

        if complete:
            ex, ey = rec_spos.x, rec_spos.y
            clock  = min(clock + self._rng.randint(2, 5), end_clock)
            self._ev(EventType.PASS, clock, period, poss_id,
                     team_id=team.team_id, player_id=carrier.player_id,
                     x=bx, y=by, end_x=ex, end_y=ey,
                     outcome=Outcome.COMPLETE, receiver_id=receiver.player_id,
                     pressure_level=pressure, snapshot_id=out_snap_id)

            if clock < end_clock:
                clock = min(clock + 1, end_clock)
                self._ev(EventType.RECEPTION, clock, period, poss_id,
                         team_id=team.team_id, player_id=receiver.player_id,
                         x=ex, y=ey)

            return ex, ey, clock, False, receiver

        else:
            # Interception: endpoint is along the pass line near the nearest defender
            ex, ey, def_spos = _interception_point(
                bx, by, rec_spos.x, rec_spos.y, def_pos, self._rng
            )

            interceptor: Player
            if def_spos is not None:
                interceptor = next(
                    (p for p in self._xi[di] if p.player_id == def_spos.player_id),
                    self._pick(di),
                )
            else:
                interceptor = self._pick(di)

            clock = min(clock + self._rng.randint(2, 5), end_clock)
            self._ev(EventType.PASS, clock, period, poss_id,
                     team_id=team.team_id, player_id=carrier.player_id,
                     x=bx, y=by, end_x=ex, end_y=ey,
                     outcome=Outcome.INCOMPLETE, receiver_id=receiver.player_id,
                     pressure_level=pressure, snapshot_id=out_snap_id)

            if clock < end_clock:
                clock = min(clock + self._rng.randint(1, 2), end_clock)
                ev    = self._rng.choice([EventType.INTERCEPTION, EventType.TACKLE])
                self._ev(ev, clock, period, poss_id,
                         team_id=dteam.team_id, player_id=interceptor.player_id,
                         x=ex, y=ey, outcome=Outcome.WON)

            return ex, ey, clock, True, interceptor

    # ------------------------------------------------------------------
    # Carry
    # ------------------------------------------------------------------

    def _do_carry(
        self,
        pi: int, di: int,
        bx: float, by: float,
        clock: int, period: int, poss_id: int,
        end_clock: int,
        carrier: Player,
    ) -> tuple[float, float, int, bool, Player]:
        team  = self._teams[pi]
        dteam = self._teams[di]

        dx  = self._rng.uniform(3.0, 14.0)
        dy  = self._rng.uniform(-6.0, 6.0)
        ex  = _cx(bx + dx)
        ey  = _cy(by + dy)
        lost = self._rng.random() < 0.14

        clock = min(clock + self._rng.randint(3, 7), end_clock)
        self._ev(EventType.CARRY, clock, period, poss_id,
                 team_id=team.team_id, player_id=carrier.player_id,
                 x=bx, y=by, end_x=ex, end_y=ey,
                 outcome=Outcome.LOST if lost else Outcome.COMPLETE)

        if lost and clock < end_clock:
            tackler = self._pick(di)
            clock   = min(clock + 1, end_clock)
            self._ev(EventType.TACKLE, clock, period, poss_id,
                     team_id=dteam.team_id, player_id=tackler.player_id,
                     x=ex, y=ey, outcome=Outcome.WON)
            return ex, ey, clock, True, tackler

        return ex, ey, clock, False, carrier

    # ------------------------------------------------------------------
    # Player selection
    # ------------------------------------------------------------------

    def _pick(self, team_idx: int) -> Player:
        xi      = self._xi[team_idx]
        weights = [_CARRIER_W.get(p.role, 1.0) for p in xi]
        return self._rng.choices(xi, weights=weights, k=1)[0]

    def _pick_kick(self, team_idx: int) -> Player:
        """Pick a central outfield player for a kickoff."""
        xi         = self._xi[team_idx]
        candidates = [p for p in xi if p.role in (Role.ST, Role.AM, Role.CM, Role.DM)]
        return self._rng.choice(candidates) if candidates else self._rng.choice(xi)

    # ------------------------------------------------------------------
    # Kickoff helper
    # ------------------------------------------------------------------

    def _emit_kickoff(
        self,
        poss_idx: int,
        clock: int,
        end_clock: int,
        period: int,
        poss_id: int,
        bx: float,
        by: float,
    ) -> tuple[int, Player]:
        kicker = self._pick_kick(poss_idx)
        clock  = min(clock + 2, end_clock)
        self._ev(EventType.KICKOFF, clock, period, poss_id,
                 team_id=self._teams[poss_idx].team_id,
                 player_id=kicker.player_id,
                 x=bx, y=by)
        return clock, kicker

    # ------------------------------------------------------------------
    # Emit helpers
    # ------------------------------------------------------------------

    def _ev(
        self,
        et: EventType,
        clock: int,
        period: int,
        poss_id: int,
        *,
        team_id: str | None = None,
        player_id: str | None = None,
        x: float | None = None,
        y: float | None = None,
        end_x: float | None = None,
        end_y: float | None = None,
        outcome: Outcome | None = None,
        receiver_id: str | None = None,
        pressure_level: float = 0.0,
        snapshot_id: str | None = None,
    ) -> None:
        self._ev_n      += 1
        self._last_clock = clock
        self._events.append(MatchEvent(
            event_id=f"ev_{self._ev_n:06d}",
            match_id=self._mid,
            scenario_id=self._sid,
            seed=self._seed,
            event_time=_EPOCH + timedelta(seconds=clock),
            match_clock_s=clock,
            period=period,
            event_type=et,
            team_id=team_id,
            player_id=player_id,
            possession_id=poss_id,
            x=x,
            y=y,
            end_x=end_x,
            end_y=end_y,
            outcome=outcome,
            receiver_id=receiver_id,
            pressure_level=pressure_level,
            snapshot_id=snapshot_id,
        ))

    def _snap_id(self) -> str:
        self._sn_n += 1
        return f"sn_{self._sn_n:06d}"
